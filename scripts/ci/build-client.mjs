import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
const root = new URL('../../', import.meta.url);
const read = name => readFileSync(new URL(name, root), 'utf8').replaceAll('\r\n', '\n');
const resource = name => JSON.parse(read('apps/api-backend/src/main/resources/ci/' + name));
const modules = [
  ['resources', 'clients/ci/src/resources.mjs'],
  ['verdictContract', 'apps/console-web/src/lib/ci-verdict-contract.mjs'],
  ['errorsProtocol', 'scripts/ci/ci-errors.mjs'],
  ['pipeline', 'scripts/ci/ci-verdict.mjs'],
  ...['contracts', 'diagnostics', 'transport', 'evidence', 'config', 'providers', 'client'].map(n => [n, `clients/ci/src/${n}.mjs`]),
];
const names = new Map(modules.map(([name, path]) => [new URL(path, root).href, 'module_' + name]));
const builtins = new Set();
function compile(name, path) {
  let source = read(path);
  if (name === 'resources') {
    const version = /export const VERSION = ('[^']+');/.exec(source)[1];
    return `const module_resources = ${JSON.stringify({ policy: resource('verdict-policy-v1.json'), catalogue: resource('export-catalog-v1.json'),
      errors: resource('error-catalog-v1.json').errors, schemas: JSON.parse(read('docs/ci/openapi-v1.json')).components.schemas })};\nmodule_resources.VERSION = ${version};\n`;
  }
  // Replace only these two known repository-resource loaders; no runtime file dependency remains.
  if (name === 'errorsProtocol') source = source.replace(/import \{ readFileSync \} from 'node:fs';[\s\S]*?const catalog = resource\('error-catalog-v1.json'\).errors;/,
    'const catalog = module_resources.errors;');
  if (name === 'pipeline') source = source.replace(/import \{ readFileSync \} from 'node:fs';\n/, '')
    .replace(/const resource=name=>[^\n]+\nconst policy=[^\n]+/, 'const {policy,catalogue,errors}=module_resources;');
  source = source.replace(/import ([^;\n]+) from '([^']+)';/g, (_all, binding, target) => {
    let dependency;
    if (target.startsWith('node:')) { dependency = 'builtin_' + target.slice(5).replaceAll(/[^a-z]/g, '_'); builtins.add(target); }
    else dependency = names.get(new URL(target, new URL(path, root)).href);
    if (!dependency) throw new Error('Unknown client build dependency');
    if (binding.startsWith('* as ')) return `const ${binding.slice(5)} = ${dependency};`;
    if (!binding.startsWith('{')) throw new Error('Unsupported client import');
    return `const ${binding.replaceAll(/\bas\b/g, ':')} = ${dependency};`;
  });
  const exports = [...source.matchAll(/export (?:async )?(?:function|const|class) (\w+)/g)].map(m => m[1]);
  source = source.replaceAll(/\bexport /g, '');
  if (/\bimport\s/.test(source) || source.includes('import.meta')) throw new Error('Unbundled runtime dependency');
  return `const module_${name} = (() => {\n${source}\nreturn {${exports.join(',')}};\n})();\n`;
}
export function distribution() {
  const body = modules.map(([name, path]) => compile(name, path)).join('\n');
  const imports = [...builtins].sort().map(target => `import * as builtin_${target.slice(5).replaceAll(/[^a-z]/g, '_')} from '${target}';`).join('\n');
  const entry = read('clients/ci/argos-ci.mjs').replace(/^#![^\n]+\n/, '').replace("import { main } from './src/client.mjs';", 'const {main} = module_client;');
  return '#!/usr/bin/env node\n// Argos CI preview: generated by scripts/ci/build-client.mjs; do not edit.\n' + imports + '\n' + body + '\n' + entry;
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const bytes = distribution();
  const checksum = createHash('sha256').update(bytes).digest('hex') + '  argos-ci.mjs\n';
  const dir = new URL('clients/ci/dist/', root);
  if (process.argv.includes('--check')) {
    if (readFileSync(new URL('argos-ci.mjs', dir), 'utf8') !== bytes || readFileSync(new URL('SHA256SUMS', dir), 'utf8') !== checksum) {
      process.stderr.write('Client distribution is stale. Run node scripts/ci/build-client.mjs\n'); process.exitCode = 1;
    }
  } else { mkdirSync(dir, { recursive: true }); writeFileSync(new URL('argos-ci.mjs', dir), bytes); writeFileSync(new URL('SHA256SUMS', dir), checksum); }
}
