"""Generate immutable Java DTOs and TypeScript types from the Clarté OpenAPI schemas.

Only the intentionally small schema subset below is accepted; unsupported types
fail rather than silently generating a weaker contract. No network/dependencies.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'apps/api-backend/src/main/resources/contracts/connected-space.openapi.json'
SCHEMAS = json.loads(SOURCE.read_text(encoding='utf-8'))['components']['schemas']

def reference(schema):
    # OpenAPI 3.0 allOf + nullable cannot make a non-nullable referenced schema
    # accept null. Use an explicit anyOf reference / null-only branch instead.
    union = schema.get('anyOf')
    if union and (not schema.get('nullable') or len(union) != 2 or
                  union[1] != {'type': 'object', 'nullable': True, 'enum': [None]}):
        raise ValueError('Only an explicit nullable reference union is supported')
    value = schema.get('$ref') or (union or [{}])[0].get('$ref')
    return value.rsplit('/', 1)[-1] if value else None

def java_type(schema):
    if reference(schema):
        return reference(schema)
    kind = schema['type']
    if kind == 'array':
        return 'List<' + java_type(schema['items']) + '>'
    if kind == 'object' and isinstance(schema.get('additionalProperties'), dict):
        return 'Map<String, ' + java_type(schema['additionalProperties']) + '>'
    return {'string': 'String', 'integer': 'Long', 'number': 'Double', 'boolean': 'Boolean'}[kind]

def ts_type(schema):
    if reference(schema):
        result = reference(schema)
    elif 'enum' in schema:
        result = ' | '.join(json.dumps(v) for v in schema['enum'])
    elif schema['type'] == 'array':
        result = 'ReadonlyArray<' + ts_type(schema['items']) + '>'
    elif schema['type'] == 'object':
        result = 'Readonly<Record<string, ' + ts_type(schema['additionalProperties']) + '>>'
    else:
        result = {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean'}[schema['type']]
    return result + (' | null' if schema.get('nullable') else '')

def validators(name, schema, required=True):
    result=[]
    nullable=schema.get('nullable', False)
    if required and not nullable:
        result.append(f'required({name}, "{name}");')
    checks=[]
    if schema.get('type') == 'string':
        for bound,op in [('minLength','<'),('maxLength','>')]:
            if bound in schema:
                checks.append(f'check({name}.codePointCount(0, {name}.length()) {">=" if op == "<" else "<="} {schema[bound]}, "{name}");')
        if 'pattern' in schema:
            checks.append(f'check(java.util.regex.Pattern.compile({json.dumps(schema["pattern"])}).matcher({name}).find(), "{name}");')
        if 'enum' in schema:
            values=', '.join(json.dumps(v) for v in schema['enum'])
            checks.append(f'check(Set.of({values}).contains({name}), "{name}");')
        if schema.get('format') == 'date-time':
            checks.append(f'java.time.Instant.parse({name});')
        if schema.get('format') == 'argos-id':
            checks.append(f'check(Long.parseLong({name}) > 0, "{name}");')
    if schema.get('type') in ['integer','number']:
        if schema['type']=='number': checks.append(f'check(Double.isFinite({name}), "{name}");')
        for bound,op in [('minimum','>='),('maximum','<=')]:
            if bound in schema:
                value=str(schema[bound]) + ('L' if schema['type']=='integer' else '.0')
                checks.append(f'check({name} {op} {value}, "{name}");')
    if schema.get('type') == 'array':
        checks.append(f'{name} = List.copyOf({name});')
        checks.append(f'check({name}.size() >= {schema.get("minItems",0)} && {name}.size() <= {schema["maxItems"]}, "{name}");')
        if schema.get('uniqueItems'): checks.append(f'check(new HashSet<>({name}).size() == {name}.size(), "{name}");')
        item_checks=validators('item',schema['items'])
        checks.append(f'for (var item : {name}) {{ ' + ' '.join(item_checks) + ' }')
    if schema.get('type')=='object': checks.append(f'{name} = Map.copyOf({name});')
    if checks:
        result.extend(['if ('+name+' != null) { '+ ' '.join(checks)+' }'] if nullable else checks)
    return result

java=['// Generated by scripts/contracts/generate-connected.py. Edit the OpenAPI source.',
      'package com.dokor.argos.services.connected.contract;', '',
      'import com.fasterxml.jackson.annotation.JsonAnySetter;',
      'import com.fasterxml.jackson.annotation.JsonInclude;',
      'import com.fasterxml.jackson.annotation.JsonProperty;',
      'import java.util.*;', '',
      'public final class ConnectedContracts {', '    private ConnectedContracts() {}',
      '    private static void required(Object value, String field) { check(value != null, field); }',
      '    private static void check(boolean valid, String field) {',
      '        if (!valid) throw new IllegalArgumentException("Invalid connected field: " + field);',
      '    }']
ts=['// Generated by scripts/contracts/generate-connected.py. Edit the OpenAPI source.','']
for name,schema in SCHEMAS.items():
    if 'enum' in schema:
        java.append('    public enum '+name+' { '+', '.join(schema['enum'])+' }')
        values=re.sub(r'(?<!^)(?=[A-Z])', '_', name).upper()+'_VALUES'
        ts.append('export const '+values+' = '+json.dumps(schema['enum'])+' as const;')
        ts.append('export type '+name+' = typeof '+values+'[number];\n')
        continue
    props=schema['properties']
    required_fields = set(schema['required'])
    if not required_fields <= set(props) or schema.get('additionalProperties') is not False:
        raise ValueError('Records must explicitly declare their closed fields: '+name)
    if any(not value.get('nullable') for field,value in props.items() if field not in required_fields):
        raise ValueError('Optional record fields must explicitly support null for older payloads: '+name)
    java.extend(['', '    @JsonInclude(JsonInclude.Include.ALWAYS)', '    public record '+name+'(',
        ',\n'.join('        @JsonProperty(value = "'+field+'", required = '+str(field in required_fields).lower()+') '+ ('@com.fasterxml.jackson.databind.annotation.JsonDeserialize(using = StrictLongDeserializer.class) ' if s.get('x-strict-integer') else '') +java_type(s)+' '+field for field,s in props.items()), '    ) {'])
    if required_fields != set(props):
        parameters = ', '.join(java_type(s)+' '+field for field,s in props.items() if field in required_fields)
        arguments = ', '.join(field if field in required_fields else 'null' for field in props)
        java.extend(['        public '+name+'('+parameters+') {', '            this('+arguments+');', '        }'])
    java.append('        public '+name+' {')
    for field,s in props.items():
        java.extend('            '+line for line in validators(field,s,field in required_fields))
    java.extend(['        }','        @JsonAnySetter public void rejectUnknown(String name, Object value) {',
        '            throw new IllegalArgumentException("Unknown connected field");', '        }','    }'])
    ts.extend(['export type '+name+' = {', *['  readonly '+field+('' if field in required_fields else '?')+': '+ts_type(s)+';' for field,s in props.items()], '};',''])
java.append('}')
outputs={ROOT/'apps/api-backend/src/main/java/com/dokor/argos/services/connected/contract/ConnectedContracts.java':'\n'.join(java)+'\n',
 ROOT/'apps/console-web/src/lib/connected/contracts.ts':'\n'.join(ts)}
parser=argparse.ArgumentParser()
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
for target,content in outputs.items():
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != content:
            raise SystemExit('Generated contract drift: '+str(target.relative_to(ROOT)))
    else:
        target.parent.mkdir(parents=True,exist_ok=True)
        target.write_text(content,encoding='utf-8',newline='\n')
print(('Verified' if args.check else 'Generated')+f' Java/TypeScript contracts from {len(SCHEMAS)} schemas')
